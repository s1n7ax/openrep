/**
 * Generates the 3D figure asset (`src/lib/three/assets/figure.glb`) from
 * MakeHuman's CC0 assets: a sculpted, athletic body skinned to the animation
 * rig, with the 17 muscle groups painted onto it for the glow (see
 * `pipeline.ts`).
 *
 * Usage:
 *   npm run generate:figure [-- --cache <dir>] [-- --out <file>]
 *
 * The MakeHuman files are pinned by commit and SHA-256 (`makehuman.ts`) and
 * downloaded once into the cache directory (default
 * node_modules/.cache/openrep-figure). The output is deterministic.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { REPO_ROOT } from '../lib/paths.ts';
import { writeGlb } from './glb.ts';
import { MAKEHUMAN_COMMIT, MAKEHUMAN_REPOSITORY, readMakeHumanFile } from './makehuman.ts';
import { buildFigure } from './pipeline.ts';

const { values } = parseArgs({
  options: {
    cache: {
      type: 'string',
      default: path.join(REPO_ROOT, 'node_modules', '.cache', 'openrep-figure'),
    },
    out: {
      type: 'string',
      default: path.join(REPO_ROOT, 'src', 'lib', 'three', 'assets', 'figure.glb'),
    },
  },
});

const figure = await buildFigure((file) => readMakeHumanFile(values.cache, file));
for (const line of figure.report) console.log(line);

const glb = writeGlb({
  positions: Float32Array.from(figure.mesh.positions),
  indices: figure.indices,
  skinIndex: figure.skinIndex,
  skinWeight: figure.skinWeight,
  muscleGroups: figure.muscles.groups,
  muscleCover: figure.muscles.cover,
  cavity: figure.cavity,
  bones: figure.bones,
  inverseBindMatrices: figure.inverseBindMatrices,
  extras: {
    source: `${MAKEHUMAN_REPOSITORY} at ${MAKEHUMAN_COMMIT}`,
    licence: 'CC0-1.0 (MakeHuman assets); generated by scripts/figure/generate-figure.ts',
  },
});
await mkdir(path.dirname(values.out), { recursive: true });
await writeFile(values.out, glb);
console.log(
  `Wrote ${path.relative(REPO_ROOT, values.out)}: ${figure.mesh.positions.length / 3} vertices, ` +
    `${figure.indices.length / 3} triangles, ${(glb.length / 1024 / 1024).toFixed(2)} MB`,
);
