/** Rectus abdominis blocks: [top, bottom, half-width at top, half-width at bottom]. */
const RECTUS_BLOCKS: readonly (readonly [number, number, number, number])[] = [
  [1.25, 1.188, 0.064, 0.064],
  [1.181, 1.132, 0.064, 0.062],
  [1.125, 1.072, 0.061, 0.058],
  [1.065, 0.885, 0.057, 0.034],
];

function rectusBlock([top, bottom, wTop, wBottom]: readonly [
  number,
  number,
  number,
  number,
]): Outline {
  const inner = 0.007;
  return [
    [inner, top],
    [(inner + wTop) / 2, top + 0.004],
    [wTop, top - 0.006],
    [(wTop + wBottom) / 2 + 0.002, (top + bottom) / 2],
    [wBottom, bottom + 0.006],
    [(inner + wBottom) / 2, bottom - 0.002],
    [inner, bottom + 0.004],
    [inner - 0.001, (top + bottom) / 2],
  ] as const;
}

