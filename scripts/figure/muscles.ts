/**
 * The muscles of the figure, drawn on the charts described in `anatomy.ts`.
 * Torso charts are in metres (x from the midline, y = height in the bind
 * pose); limb charts in (θ degrees, u along the bone). Every muscle with a
 * group lights up with that group; muscles without one are only sculpted.
 *
 * Landmarks of the bind-pose body (front): sternal notch (0, 1.52), clavicles
 * along y ≈ 1.50, nipples (0.09, 1.30), xiphoid (0, 1.24), navel (0, 1.105),
 * front hip bone (0.12, 0.97), pubis (0, 0.86), armpit (0.19, 1.36).
 * Back: C7 (0, 1.53), scapula from y 1.45 to its lower tip (0.09, 1.29),
 * acromion (0.18, 1.47), iliac crest y ≈ 1.04, buttock fold y ≈ 0.81.
 */
